#!/usr/bin/env python3
"""The proof-space pilot contract (G9, PS-01) as data: tools/pilot-contract.json is the source and
PILOT.md its view. The kinds, limits and result tables are rendered from warrant_pilot/pilot.py itself.
Unlike the views of the record graph (build artifacts since G11), PILOT.md stays committed and
byte-compared, as SPEC.md does: it is the published contract, the accepted PS-02..PS-04 closures cite
it by digest, and it changes only with the contract, never with the records.

    python3 tools/pilot.py project      # regenerate PILOT.md
    python3 tools/pilot.py check        # refuse a differing PILOT.md or a row that holds nothing

Each row of the contract is exactly one of: enforced (`tests`: cases of tests/pilot_test.py that
passed, and `mutants`: ids of tests/mutants.py whose own test file is pilot_test and whose targets
include one of those cases), `deferred` to a G9 obligation filed in .warrant/records.jsonl (a Codex card such
as PS-05+06, rendered with its duty id), or `excluded` from the pilot with the reason. `check` here
sees no test results; tests/pilot_test.py K1 runs `problems` with its own, and also requires every
case of that file to be some mutant's target. Refusals print as `REFUSED <CODE> <detail>`."""
import importlib.util
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, os.environ.get("WARRANT_IMPL") or str(ROOT))

from warrant.store import Store              # noqa: E402
from warrant_pilot import pilot as PL         # noqa: E402

SOURCE = "tools/pilot-contract.json"
VIEW = "PILOT.md"
TEST = "pilot_test"
ENFORCEMENT = ("tests", "deferred", "excluded")


def _table(name):
    if name == "kinds":
        rows = [f"| `{k}` | {v.tag_doc} | {v.deps_doc} |" for k, v in PL.KINDS.items()]
        return ["| kind | tag, checked on the bytes first | dependency fields (all required) |", "| --- | --- | --- |", *rows]
    if name == "limits":
        rows = [f"| `{k}` | {v:,} |".replace(",", " ") for k, v in PL.LIMITS.items()]
        return ["| limit | default |", "| --- | --- |", *rows]
    if name == "codes":
        rows = [f"| {res} | " + ", ".join(f"`{c}`" for c, r in PL.CODES.items() if r == res) + " |"
                for res in (PL.INCONCLUSIVE, PL.REFUSED)]
        return ["| result | codes |", "| --- | --- |", f"| {PL.RESOLVED} | none |", *rows]
    raise KeyError(name)


def _status(row, cards):
    if "tests" in row:
        return "enforced: " + ", ".join(row["tests"]) + " · " + ", ".join(row["mutants"])
    if "deferred" in row:
        return f"deferred to {row['deferred']}, duty `{str(cards.get(row['deferred']))[:12]}`"
    return f"excluded: {row['excluded']}"


def render(contract, cards):
    """PILOT.md: the contract's text, its tables from warrant/pilot.py, each row with its status."""
    out = [f"# {contract['title']}", "", f"`{contract['contract']}`. Generated by `python3 tools/pilot.py project` "
           f"from `{SOURCE}`; `tools/pilot.py check` and `tests/pilot_test.py` K1 refuse a differing file.", ""]
    for para in contract["intro"]:
        out += [para, ""]
    for sec in contract["sections"]:
        card = f" ({sec['card']}, duty `{str(cards.get(sec['card']))[:12]}`)" if sec.get("card") else ""
        out += [f"## {sec['title']}{card}", ""]
        for para in sec.get("text", []):
            out += [para, ""]
        if sec.get("table"):
            out += _table(sec["table"]) + [""]
        for row in sec["rows"]:
            out.append(f"- **{row['id']}** {row['rule']} *({_status(row, cards)})*")
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def problems(contract, view, cases, mutants, cards):
    """[(code, detail)]: what keeps the contract from holding. `cases` ({case: PASS|FAIL} of tests/pilot_test.py,
    or None when no test ran), `mutants` the harness's list, `cards` {card: duty id} of the filed G9 obligations."""
    out = []
    by_id = {m[0]: m for m in mutants}
    if view != render(contract, cards):
        out.append(("STALE_VIEW", f"{VIEW} is not the rendering of {SOURCE}"))
    rows = [r for s in contract["sections"] for r in s["rows"]]
    if not rows or not any("tests" in r for r in rows):
        out.append(("NO_ROWS", "a contract with no enforced row establishes nothing"))
    ids = [r["id"] for r in rows]
    out += [("DUPLICATE_ID", i) for i in sorted({i for i in ids if ids.count(i) > 1})]
    for sec in contract["sections"]:
        if sec.get("card") and sec["card"] not in cards:
            out.append(("UNKNOWN_CARD", f"section {sec['title']!r} names {sec['card']}, no filed G9 obligation"))
    for r in rows:
        out += _row_problems(r, cases, by_id, cards)
    if cases is not None:
        targeted = {t for m in mutants if m[4] == TEST for t in m[5]}
        out += [("UNTARGETED_CASE", f"{c} is no mutant's target: CI runs {TEST} only in the mutant baseline")
                for c in sorted(set(cases) - targeted)]
    return out


def _row_problems(r, cases, by_id, cards):
    """What keeps one row of the contract from holding: its shape, its card, its cases and its mutants."""
    kinds = [k for k in ENFORCEMENT if k in r]
    if len(kinds) != 1 or ("tests" in r) != ("mutants" in r):
        return [("ROW_SHAPE", f"{r['id']} is not exactly one of enforced (tests and mutants), deferred, excluded")]
    out = []
    if "deferred" in r and r["deferred"] not in cards:
        out.append(("UNKNOWN_CARD", f"{r['id']} is deferred to {r['deferred']}, no filed G9 obligation"))
    if "tests" not in r:
        return out
    if not (r["tests"] and r["mutants"]):
        out.append(("ROW_SHAPE", f"{r['id']} is enforced by no case or no mutant"))
    for t in r["tests"]:
        if cases is not None and t not in cases:
            out.append(("UNKNOWN_CASE", f"{r['id']} cites {t}, not a case of {TEST}"))
        elif cases is not None and cases[t] != "PASS":
            out.append(("UNPASSED_CASE", f"{r['id']} cites {t}, which did not pass"))
    return out + _mutant_problems(r, by_id)


def _mutant_problems(r, by_id):
    out = []
    for mid in r["mutants"]:
        m = by_id.get(mid)
        if m is None:
            out.append(("UNKNOWN_MUTANT", f"{r['id']} cites {mid}, not in tests/mutants.py"))
        elif m[4] != TEST or not set(m[5]) & set(r["tests"]):
            out.append(("MUTANT_OFF_ROW", f"{r['id']} cites {mid}, which targets {m[4]} {m[5]}, none of its cases"))
    return out


def _v2_ids(snap):
    """{record id: its Warrant 2 id} of the migrated records, from the migrations' maps: PILOT.md keeps the duty ids it
    was rendered with, and the accepted closures cite its digest."""
    v2 = {}
    for envs in snap.lines.values():
        rec = envs[0]["record"]
        doc = snap.json_blob(rec["body"]["target"]) if rec["schema"] == "migration@1" else None
        for row in (doc or {}).get("map", []) if isinstance(doc, dict) else []:
            if len(row[1]) == 1:
                v2[row[0]] = row[1][0]
    return v2


def filed_cards(root=ROOT):
    """{card: obligation lineage} of the obligation@1 lineages in `root`'s .warrant/records.jsonl whose statement names
    a Codex card `(Codex PS-..`."""
    snap = Store(Path(root) / ".warrant").snapshot()
    v2 = _v2_ids(snap)
    out = {}
    for rid, envs in sorted(snap.lines.items()):
        rec = envs[0]["record"]
        text = rec["body"].get("statement", "") if rec["schema"] == "obligation@1" and rec["lineage"] is None else ""
        if "(Codex PS-" in text:
            out[text.split("(Codex ", 1)[1].split(";")[0].split(")")[0]] = v2.get(rid, rid)
    return out


def mutant_list(root=ROOT):
    """tests/mutants.py's rows as (id, file, find, replace, test file name, cases)."""
    spec = importlib.util.spec_from_file_location("warrant_mutants", Path(root) / "tests" / "mutants.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return [(m[0], m[1], m[2], m[3], Path(m[4]).stem, m[5]) for m in mod.MUTANTS]


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if argv not in (["project"], ["check"]):
        print(__doc__)
        return 2
    contract = json.loads((ROOT / SOURCE).read_text())
    cards = filed_cards()
    if argv == ["project"]:
        (ROOT / VIEW).write_text(render(contract, cards))
        print(f"wrote {VIEW}")
        return 0
    probs = problems(contract, (ROOT / VIEW).read_text(), None, mutant_list(), cards)
    for code, detail in probs:
        print(f"REFUSED {code} {detail}")
    if not probs:
        print(f"OK {VIEW}: {sum(len(s['rows']) for s in contract['sections'])} rows")
    return 1 if probs else 0


if __name__ == "__main__":
    sys.exit(main())
