class Reviews:
    def __init__(self, root):
        self.root = Path(root)
        self.repo = Repo(self.root)
        self.view = self.root / VIEW

    def config(self):
        return config(self.root)

    def model(self):
        return Model(self.repo.snapshot(), self.repo.trust(), self.config(), self.repo.roles()[0])


class Writer:
    def __init__(self, rv, key, actor):
        self.rv, self.key, self.actor = rv, key, actor
        self.store = Store(rv.repo.store_dir).init()
        self.m = rv.model()
        self.cfg = self.m.cfg

    def at(self):
        return max([int(time.time())] + [r["at"] for r in self.m.recs.values()])

    def file(self, rtype, body, blobs=()):
        """Validate the record first, then store its blobs and it: a refused command writes nothing."""
        rec = R.record(rtype, self.actor, self.at(), body)
        for doc in blobs:
            self.store.put_json(doc)
        return self.store.append(rtype, self.actor, rec["at"], body, self.key, self.rv.repo.trust())

    def holder(self, rv):
        r = self.m.rep["duties"][rv.did]
        if r["holder"] != self.actor and self.actor not in r["delegates"]:
            raise Refused(f"#{rv.pr}'s duty is held by {r['holder']}, not {self.actor}", "REVIEW_NOT_HOLDER")

    def open(self, pr, title, serves=()):
        if not (type(pr) is int and pr > 0):
            raise Refused("--pr is a pull request number", "REVIEW_TEXT")
        if pr in self.m.reviews:
            raise Refused(f"#{pr} has a review duty already: {self.m.reviews[pr].did[:12]}", "REVIEW_DUTY_EXISTS")
        statement = f"{self.cfg['repository']}#{pr} is fit to merge: {one_line(title, '--title', 380)}"
        if not STATEMENT.match(statement) or len(statement) > 400:
            raise Refused("the duty statement is at most 400 characters", "REVIEW_TEXT")
        srv = list(dict.fromkeys(self.m.resolve_duty(x) for x in serves))
        return self.file("duty", R.duty(self.actor, statement, self.cfg["owed_to"], {"attest": {}},
                                        accept_by=self.cfg["accept_by"], serves=srv))

    def head(self, pr, commit, answers=()):
        rv = self.m.review(pr)
        self.holder(rv)
        commit, tree = canonical(self.rv.root, commit)
        if not is_ancestor(self.rv.root, commit):
            raise Refused(f"{commit[:12]} is not an ancestor of HEAD: a head's closure is committed on top of it",
                          "REVIEW_COMMIT_NOT_ANCESTOR")
        last = rv.latest()
        if last is not None and last.commit == commit:
            raise Refused(f"head {last.n} of #{pr} is {commit[:12]} already", "REVIEW_HEAD_SAME")
        # The merges in the head's history are observed in the head's own store, so the reviewer reviews them
        # with it (their records after it would be unreviewed, eligibility.tail_records).
        missing = unobserved(self.rv.root, Model(store_at(self.rv.root, commit), self.rv.repo.trust(), self.cfg), commit)
        if missing:
            raise Refused(f"{commit[:12]}'s store holds no merge observation of "
                          + ", ".join(f"#{n} (merged at {mc[:12]})" for n, mc in missing)
                          + ": run tools/review.py merged --due, commit its records and name that commit",
                          "REVIEW_MERGE_UNOBSERVED")
        mine = {f.cid: f for f in rv.findings}
        for a in answers:
            if a not in mine or mine[a].answered_by is not None:
                raise Refused(f"{a[:12]} is not an unanswered finding against a head of #{pr}", "REVIEW_ANSWER_UNKNOWN")
        admitted = [h.tid for h in rv.heads if h.verdict == "ADMITTED"]
        doc = {"schema": HEAD, "duty": rv.did, "pr": pr, "commit": commit, "tree": tree,
               "previous": last.tid if last else None, "answers": sorted(set(answers))}
        h = C.digest(C.canon(doc))
        item = R.item(rv.did, "revalidate", [h], revalidates=admitted) if admitted else R.item(rv.did, "discharge", [h])
        body = R.transition("ATTESTED", [h], closes=[item], established=[head_established(self.cfg, pr, commit, tree)],
                            residual=[HEAD_RESIDUAL], subject=commit)
        return self.file("transition", body, [doc])

    def current(self, rv, commit):
        """The current head of `rv`, which `commit` must name by its full id."""
        if not is_commit(commit):
            raise Refused(f"{str(commit)[:50]!r} is not a full lowercase commit id: name the head you reviewed, "
                          "never a ref", "REVIEW_COMMIT_NAME")
        last = rv.latest()
        if last is None:
            raise Refused(f"#{rv.pr} has no head closure yet", "REVIEW_NOT_A_HEAD")
        if last.commit != commit:
            old = next((h for h in rv.heads if h.commit == commit), None)
            raise Refused(f"{commit[:12]} is " + (f"head {old.n}, superseded by head {last.n} ({last.commit[:12]})" if old
                                                  else f"no head of #{rv.pr}"),
                          "REVIEW_HEAD_SUPERSEDED" if old else "REVIEW_NOT_A_HEAD")
        return last

    def finding(self, pr, commit, severity, what, where=(), test=None):
        rv = self.m.review(pr)
        h = self.current(rv, commit)
        if severity not in SEVERITIES:
            raise Refused(f"--severity is one of {list(SEVERITIES)}", "REVIEW_TEXT")
        one_line(what, "--what", 400)
        for w in where:
            one_line(w, "--where", 200)
        if len(where) > MAX_WHERE:
            raise Refused(f"at most {MAX_WHERE} --where", "REVIEW_TEXT")
        if test is not None and RR.test_problem(test):
            raise Refused(RR.test_problem(test), "REVIEW_FINDING_TEST")
        doc = {"schema": FINDING, "duty": rv.did, "pr": pr, "head": h.tid, "commit": h.commit, "tree": h.tree,
               "severity": severity, "what": what, "where": list(where), "test": test}
        hh = C.digest(C.canon(doc))
        return self.file("challenge", R.challenge(h.tid, f"{severity} {what}", [hh], item_index=0), [doc])

    def accept(self, pr, commit):
        rv = self.m.review(pr)
        if self.actor not in rv.rec["body"]["accept_by"]:
            raise Refused(f"{self.actor} is not in the accept_by of #{pr}'s duty ({', '.join(rv.rec['body']['accept_by'])})",
                          "NOT_AN_ACCEPTOR")
        h = self.current(rv, commit)
        if h.verdict != "PENDING" or self.actor not in h.waiting:
            raise Refused(f"head {h.n} of #{pr} is {h.verdict}, not awaiting {self.actor}'s acceptance", "NOT_PENDING")
        return self.file("accept", R.accept(h.tid, 0, h.item["evidence"]))

    def merged(self, pr, merge):
        rv = self.m.review(pr)
        if not is_ancestor(self.rv.root, canonical(self.rv.root, merge)[0]):
            raise Refused(f"{merge[:12]} is not an ancestor of HEAD", "REVIEW_COMMIT_NOT_ANCESTOR")
        if rv.merges:
            raise Refused(f"#{pr} has a merge observation already", "REVIEW_MERGE_TWICE")
        rep = merge_report(self.rv.root, self.rv.repo.trust(), self.cfg, rv, merge)
        probe = {"probe": MERGE, "duty": rv.did, "pr": pr, "merge": rep["merge"]}
        now = self.at()
        body = R.observation(merge_target(self.cfg, pr), C.digest(C.canon(probe)), [now, now],
                             f"merged {rep['merge']} tip {rep['tip']}", [C.digest(C.canon(rep))])
        return self.file("observation", body, [probe, rep])

    def merged_due(self):
        """A merge observation of each pull request with a review duty and none yet that merged into HEAD's
        history (unobserved): [(pull request, merge commit, observation id)], by this writer. The merges are
        Git's (merge_of), never a choice; an ambiguous one refuses the whole command before anything is filed."""
        due = unobserved(self.rv.root, self.m, resolve(self.rv.root, "HEAD"))
        return [(n, mc, self.merged(n, mc)) for n, mc in due]

    def replay(self, pr=None):
        """The review replay checker: one observation per mechanical finding and head from its own on that no
        adopted replayer of this identity has observed. [(finding, commit, result, observation id)]."""
        me = RR.actor()
        if self.actor != me:
            raise Refused(f"replay signs as {me[:28]}…, this checkout's {RR.SELF}", "REVIEW_REPLAYER_KEY")
        if me not in self.cfg["replayers"]:
            raise Refused(f".warrant/reviews.json adopts no replayer {me[:28]}…", "REVIEW_REPLAYER_UNPINNED")
        todo = [(rv, f, h) for rv in sorted(self.m.reviews.values(), key=lambda x: x.pr) if pr in (None, rv.pr)
                for f in rv.findings if f.test is not None
                for h in rv.heads if h.n >= f.head.n and f.at(h.commit) is None]
        return [self._replay_one(rv, f, h) for rv, f, h in todo]

    def _replay_one(self, rv, f, h):
        commit, tree = canonical(self.rv.root, h.commit)
        if tree != h.tree:
            raise Refused(f"head {h.n} of #{rv.pr}: {commit[:12]} has tree {tree[:12]}", "REVIEW_COMMIT_NAME")
        t0 = int(time.time())
        result = RR.run(self.rv.root, commit, f.test)
        probe = {"probe": RR.PROBE, "finding": f.cid, "commit": commit, "tree": tree,
                 "test": f"{f.test['file']}:{f.test['case']}"}
        now = self.at()
        body = R.observation(replay_target(self.cfg, rv.pr, f.cid, commit), C.digest(C.canon(probe)),
                             [min(t0, now), now], result)
        oid = self.file("observation", body, [probe])
        self.m = self.rv.model()
        return f.cid, commit, result, oid


def head_established(cfg, pr, commit, tree):
    return f"{cfg['repository']}#{pr} head {commit} tree {tree}"


# ---------------------------------------------------------------- check

def base_ids(root, base):
    """The record ids at revision `base` (resolved once to its commit id)."""
    rows = _git(root, "ls-tree", "-r", "--name-only", ids=(resolve(root, base),), paths=(f"{STORE}/records",)).decode().split()
    return {Path(p).name[:-5] for p in rows if p.endswith(".json")}


def new_problems(rv, model, before):
    """[(code, detail)] of the review records new since the base, read against this repository's history:
    every new head's commit is canonical with its tree and an ancestor of HEAD; every new merge
    observation's report is the one this history gives."""
    out = [x for h in model.heads.values() if h.tid not in before for x in _head_problems(rv, h)]
    for r in model.reviews.values():
        out += [x for oid, _, rep in r.merges if oid not in before for x in _merge_problems(rv, model, r, oid, rep)]
    return out


def _head_problems(rv, h):
    try:
        _, tree = canonical(rv.root, h.commit)
    except Refused as e:
        return [("REVIEW_COMMIT_NAME", f"head {h.tid[:12]}: {e}")]
    if tree != h.tree:
        return [("REVIEW_COMMIT_NAME", f"head {h.tid[:12]}: {h.commit[:12]} has tree {tree[:12]}, the blob says "
                 f"{h.tree[:12]}")]
    if not is_ancestor(rv.root, h.commit):
        return [("REVIEW_COMMIT_NOT_ANCESTOR", f"head {h.tid[:12]}: {h.commit[:12]} is not an ancestor of HEAD")]
    return []


def _merge_problems(rv, model, r, oid, rep):
    try:
        want = merge_report(rv.root, rv.repo.trust(), model.cfg, r, rep["merge"])
    except (Refused, subprocess.CalledProcessError) as e:
        return [("REVIEW_MERGE_REPORT", f"merge observation {oid[:12]}: {e}")]
    if want != rep:
        return [("REVIEW_MERGE_REPORT", f"merge observation {oid[:12]} of #{r.pr}: this history gives tip "
                 f"{want['tip'][:12]}, {len(want['accepted'])} accepted head(s), outside {want['outside']}")]
    if not is_ancestor(rv.root, rep["merge"]):
        return [("REVIEW_COMMIT_NOT_ANCESTOR", f"merge observation {oid[:12]}: {rep['merge'][:12]} is not an "
                 "ancestor of HEAD")]
    return []


def check(rv, base=None):
    """[(code, detail)]: empty iff the review records are well formed and REVIEWS.md is their view."""
    try:
        m = rv.model()
    except Refused as e:
        return [(e.code or "REVIEW_CONFIG", str(e))]
    out = list(m.problems)
    if m.cfg["replayers"][-1] != RR.actor((rv.root / RR.SELF).read_bytes() if (rv.root / RR.SELF).is_file() else None):
        out.append(("REVIEW_REPLAYER_STALE", f".warrant/reviews.json's current replayer is not this checkout's {RR.SELF}"))
    if not rv.view.is_file():
        out.append(("REVIEWS_MISSING", "REVIEWS.md does not exist; run tools/review.py project"))
    elif rv.view.read_bytes() != render_view(m).encode():     # bytes: read_text() would turn \r\n into \n
        out.append(("REVIEWS_STALE", "REVIEWS.md is not the view of the records; run tools/review.py project"))
    if base is not None:
        try:
            before = base_ids(rv.root, base)
        except (Refused, subprocess.CalledProcessError) as e:
            return out + [("BASE_UNREADABLE", f"{base}: {e}")]
        out += new_problems(rv, m, before)
    return out


def verify(rv, base):
    """[(code, detail)]: each replay observation new since `base` re-executed by this checkout's
    review_replay.py, which must be the observer (REVIEW_REPLAYER_CODE), at the observed commit, which
    must be canonical with the observed tree; a result other than the observed one is REVIEW_REPLAY_DIFFERS."""
    m, before, me = rv.model(), base_ids(rv.root, base), RR.actor()
    return [x for f in m.findings.values() for commit, (oid, result) in sorted(f.observed.items()) if oid not in before
            for x in _reexecute(rv, m, f, commit, oid, result, me)]


def _reexecute(rv, m, f, commit, oid, result, me):
    if m.recs[oid]["actor"] != me:
        return [("REVIEW_REPLAYER_CODE", f"replay {oid[:12]} is by {m.recs[oid]['actor'][:28]}…, this "
                 f"checkout's {RR.SELF} is {me[:28]}…: re-execute it with that code")]
    try:
        c, tree = canonical(rv.root, commit)
    except Refused as e:
        return [("REVIEW_COMMIT_NAME", f"replay {oid[:12]}: {e}; nothing run")]
    head = next(h for h in m.by_duty[f.head.item["duty"]].heads if h.commit == c)
    if tree != head.tree:
        return [("REVIEW_COMMIT_NAME", f"replay {oid[:12]}: {c[:12]} has tree {tree[:12]}; nothing run")]
    got = RR.run(rv.root, c, f.test)
    if got != result:
        return [("REVIEW_REPLAY_DIFFERS", f"replay {oid[:12]} of finding {f.cid[:12]} at {c[:12]}: observed "
                 f"{result}, re-executed {got}")]
    return []


def summary(m):
    fs = list(m.findings.values())
    merged = [rv for rv in m.reviews.values() if rv.merges]
    return (f"{len(m.reviews)} pull requests ({sum(m.rep['duties'][rv.did]['disposition'] == 'DISCHARGED' for rv in m.reviews.values())}"
            f" accepted), {len(fs)} findings ({sum(finding_class(f) == 'REPRODUCED' for f in fs)} reproduced, "
            f"{sum(f.test is None for f in fs)} theses, {sum(f.answered_by is not None for f in fs)} answered), "
            f"{len(merged)} merged ({sum(merged_without_acceptance(rv.merges[0][2]) for rv in merged)} without reviewer "
            "acceptance of the result)")


