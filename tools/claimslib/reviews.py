def one_line(text, what, limit, code="REVIEW_TEXT"):
    if not (isinstance(text, str) and text and text.strip() == text and len(text) <= limit
            and not any(c in text for c in "\r\n")):
        raise Refused(f"{what} is one line of at most {limit} characters with no space at either end", code)
    return text


def is_line(text, limit):
    try:
        one_line(text, "", limit)
        return True
    except Refused:
        return False


def config(root):
    p = Path(root) / DOT / "reviews.json"
    try:
        cfg = json.loads(p.read_text())
    except (OSError, ValueError) as e:
        raise Refused(f".warrant/reviews.json: {e}", "REVIEW_CONFIG") from e
    return check_config(cfg)


def check_config(cfg):
    """The parsed .warrant/reviews.json, refused unless well formed (the merge gate reads it from the base)."""
    if not (isinstance(cfg, dict) and set(cfg) == set(CONFIG_FIELDS) and cfg["reviews"] == CONFIG
            and isinstance(cfg["repository"], str) and REPOSITORY.match(cfg["repository"])
            and all(isinstance(cfg[k], list) and all(S.is_actor(a) for a in cfg[k]) for k in CONFIG_FIELDS[2:])
            and cfg["owed_to"] and cfg["accept_by"] and cfg["replayers"]):
        raise Refused(f".warrant/reviews.json members are {list(CONFIG_FIELDS)}, reviews {CONFIG!r}, a repository "
                      "owner/name, and non-empty lists of actor ids", "REVIEW_CONFIG")
    return cfg


def is_commit(v):
    """A full lowercase Git object id (SHA-1 or SHA-256 object format: shapes.hex_of), never a ref."""
    return S.hex_of(v, 40) or S.hex_of(v, 64)


def ledger_path(p):
    return p.startswith(LEDGER_DIR) or p in LEDGER_FILES


# ---------------------------------------------------------------- the model

class Head:
    def __init__(self, tid, rec, blob):
        self.tid, self.rec, self.blob = tid, rec, blob
        self.commit, self.tree, self.previous, self.answers = blob["commit"], blob["tree"], blob["previous"], blob["answers"]
        self.item = rec["body"]["closes"][0]
        self.n, self.verdict, self.waiting, self.accepted_by, self.successor = 0, None, [], [], None


class Finding:
    def __init__(self, cid, rec, blob, head):
        self.cid, self.rec, self.blob, self.head = cid, rec, blob, head
        self.test = blob["test"]
        self.observed = {}          # commit -> (observation id, result), by an adopted replayer
        self.answered_by = None

    def at(self, commit):
        """The replay result at `commit`, or None when no adopted replayer observed it."""
        got = self.observed.get(commit)
        return got[1] if got else None


class Review:
    def __init__(self, did, rec, pr, title):
        self.did, self.rec, self.pr, self.title = did, rec, pr, title
        self.heads, self.findings, self.merges, self.others = [], [], [], []
        self.fork = False

    def latest(self):
        if self.fork:
            raise Refused(f"#{self.pr}'s heads fork: two closures name the same previous head", "REVIEW_HEAD_FORK")
        return self.heads[-1] if self.heads else None


class Model:
    """The reviews a snapshot holds under a trust, assessed once."""

    def __init__(self, snap, trust, cfg, roles=None, assess=True):
        """`assess=False` (the witness ledger) leaves the engine out: no verdicts, no dispositions."""
        self.snap, self.cfg = snap, cfg
        self.recs, _ = authentic(snap, trust)
        as_of = max((r["at"] for r in self.recs.values()), default=0)
        self.rep = E.assess(snap, trust, as_of, E.profile()) if assess else None
        self.problems = []
        self._accepts = accept_index(self.recs)
        self.reviews, self.by_duty, self.heads, self.findings = {}, {}, {}, {}
        self._duties()
        self._heads()
        self._late_accepts()
        self._findings()
        self._answers()
        self._observations()
        if roles is not None:
            self.problems += unpinned(roles, cfg["owed_to"] + cfg["accept_by"] + cfg["replayers"], ".warrant/reviews.json")

    def problem(self, code, detail):
        self.problems.append((code, detail))

    def blob(self, h):
        doc = self.snap.json_blob(h) if S.hex64(h) else None
        return doc if isinstance(doc, dict) else None

    def _duties(self):
        cfg = self.cfg
        for did, r in sorted(self.recs.items(), key=lambda kv: (kv[1]["at"], kv[0])):
            if r["type"] != "duty":
                continue
            b = r["body"]
            m = STATEMENT.match(b["statement"])
            if not m or m.group("repo") != cfg["repository"]:
                continue
            pr = int(m.group("pr"))
            terms = (b["owed_to"], b["accept_by"], b["release_by"], b["condition"], b["requires"], b["answers"],
                     b["subject"], b["schedule"])
            if terms != (cfg["owed_to"], cfg["accept_by"], [], {"attest": {}}, [], None, None, None):
                # Open circle: anyone may bind a key; a review its author's accomplice accepts would close unreviewed.
                self.problem("REVIEW_TERMS", f"duty {did[:12]} (#{pr}) is owed to {b['owed_to']}, accepted by "
                             f"{b['accept_by']}, released by {b['release_by']}; .warrant/reviews.json says owed_to "
                             f"{cfg['owed_to']}, accept_by {cfg['accept_by']}, an attest condition and nothing else")
                continue
            if pr in self.reviews:
                self.problem("REVIEW_DUTY_FORK", f"duty {did[:12]} is a second review duty of #{pr} "
                             f"(the first is {self.reviews[pr].did[:12]})")
                continue
            self.reviews[pr] = self.by_duty[did] = Review(did, r, pr, m.group("title"))

    def _head_blob(self, tid, r, rv):
        """The head blob of closure `tid` of review `rv`, or None (a problem) when it is not one."""
        b = r["body"]
        m = b["closes"][0]
        docs = [self.blob(h) for h in m["evidence"]]
        doc = docs[0] if len(docs) == 1 and b["evidence"] == m["evidence"] else None
        if not (doc is not None and doc.get("schema") == HEAD and set(doc) == set(HEAD_FIELDS)):
            self.problem("REVIEW_HEAD_SHAPE", f"transition {tid[:12]} closes #{rv.pr}'s duty and its one evidence is "
                         f"not one {HEAD} blob")
            return None
        if not (is_commit(doc["commit"]) and is_commit(doc["tree"])):
            self.problem("REVIEW_COMMIT_NAME", f"head {tid[:12]} of #{rv.pr} names commit {str(doc['commit'])[:50]!r} and "
                         f"tree {str(doc['tree'])[:50]!r}: a head is named by full lowercase object ids, never a ref")
            return None
        ok = (doc["duty"] == rv.did and doc["pr"] == rv.pr and b["subject"] == doc["commit"]
              and (doc["previous"] is None or S.hex64(doc["previous"]))
              and isinstance(doc["answers"], list) and all(S.hex64(x) for x in doc["answers"])
              and doc["answers"] == sorted(set(doc["answers"])))
        if not ok:
            self.problem("REVIEW_HEAD_SHAPE", f"head {tid[:12]} of #{rv.pr}: its blob names another duty or number, its "
                         "subject is not its commit, or previous/answers are malformed")
            return None
        return doc

    def _heads(self):
        for tid, r in sorted(self.recs.items()):
            if r["type"] != "transition":
                continue
            mine = [m for m in r["body"]["closes"] if m["duty"] in self.by_duty]
            if not mine:
                continue
            rv = self.by_duty[mine[0]["duty"]]
            if len(r["body"]["closes"]) != 1:
                self.problem("REVIEW_HEAD_SHAPE", f"transition {tid[:12]} closes #{rv.pr}'s duty among other items")
                continue
            if mine[0]["act"] not in ("discharge", "revalidate"):
                rv.others.append((tid, mine[0]["act"]))           # a release by owed_to, an impossible, a transfer
                continue
            if r["actor"] != rv.rec["actor"]:
                # A head is the author's: another actor's closure would fork the lineage (the engine
                # finds it OVERCLAIMED; here it is not a head). Delegated heads are not supported.
                self.problem("REVIEW_HEAD_FILER", f"transition {tid[:12]} closes #{rv.pr}'s duty, filed by "
                             f"{r['actor'][:28]}, not its author {rv.rec['actor'][:28]}")
                continue
            doc = self._head_blob(tid, r, rv)
            if doc is not None:
                self.heads[tid] = Head(tid, r, doc)
                rv.heads.append(self.heads[tid])
        for rv in self.reviews.values():
            self._lineage(rv)

    def _successors(self, rv):
        """{previous closure (None for the first head): [heads naming it]}; a previous that is no head
        of this pull request is a problem."""
        mine = {h.tid: h for h in rv.heads}
        succ = {}
        for h in rv.heads:
            if h.previous is not None and h.previous not in mine:
                self.problem("REVIEW_HEAD_SHAPE", f"head {h.tid[:12]} of #{rv.pr} names previous {h.previous[:12]}, "
                             "not a head of this pull request")
            else:
                succ.setdefault(h.previous, []).append(h)
        return succ

    def _lineage(self, rv):
        succ = self._successors(rv)
        forks = [p for p, hs in succ.items() if len(hs) > 1]
        if forks:
            rv.fork = True
            self.problem("REVIEW_HEAD_FORK", f"#{rv.pr}: {'two first heads' if None in forks else 'two heads name the same previous'}"
                         f" ({', '.join(h.tid[:12] for p in forks for h in succ[p])})")
        roots = [h for h in rv.heads if h.previous is None]
        order, cur, seen = [], (roots[0] if len(roots) == 1 else None), set()
        while cur is not None and cur.tid not in seen:
            seen.add(cur.tid)
            order.append(cur)
            nxt = succ.get(cur.tid, [])
            cur = nxt[0] if len(nxt) == 1 else None
        rest = sorted((h for h in rv.heads if h.tid not in seen), key=lambda h: (h.rec["at"], h.tid))
        rv.heads = order + rest
        self._verdicts(rv)

    def _verdicts(self, rv):
        cands = {(c["transition"], c["item"]): c for c in self.rep["duties"][rv.did]["candidates"]} if self.rep else {}
        for i, h in enumerate(rv.heads):
            h.n = i + 1
            h.successor = rv.heads[i + 1] if i + 1 < len(rv.heads) and not rv.fork else None
            c = cands.get((h.tid, 0), {})
            h.verdict, h.waiting = c.get("verdict"), c.get("waiting_for", [])
            h.accepted_by = acceptors(self.recs, self._accepts, h.tid, 0)

    def _late_accepts(self):
        """An acceptance of a head filed after the next head (strictly later `at`) accepts what is no longer
        the pull request: refused, as a finding against a superseded head is."""
        for aid, r in sorted(self.recs.items()):
            h = self.heads.get(r["body"]["transition"]) if r["type"] == "accept" else None
            if h is None:
                continue
            rv = self.by_duty[h.item["duty"]]
            later = [s for s in rv.heads if s.n > h.n and s.rec["at"] < r["at"]]
            if later:
                self.problem("REVIEW_ACCEPT_SUPERSEDED", f"accept {aid[:12]} by {r['actor'][:28]} of head {h.n} of "
                             f"#{rv.pr} was filed when head {later[0].n} ({later[0].commit[:12]}) had superseded it")

    def _findings(self):
        for cid, r in sorted(self.recs.items()):
            f = self._finding(cid, r) if r["type"] == "challenge" else None
            if f is not None:
                self.findings[cid] = f
                self.by_duty[f.head.item["duty"]].findings.append(f)

    def _finding(self, cid, r):
        """The Finding challenge `cid` is, or None (a problem when it carries a finding or targets a head)."""
        b = r["body"]
        docs = [self.blob(h) for h in b["evidence"]]
        h = self.heads.get(b["target"])
        if h is None:
            if any(d is not None and d.get("schema") == FINDING for d in docs):
                self.problem("REVIEW_FINDING_HEAD", f"challenge {cid[:12]} carries a finding and targets "
                             f"{b['target'][:12]}, not the closure of a pull request's head")
            return None
        rv = self.by_duty[h.item["duty"]]
        doc = docs[0] if len(docs) == 1 else None
        if not (doc is not None and doc.get("schema") == FINDING and set(doc) == set(FINDING_FIELDS)
                and b["item"] == 0):
            self.problem("REVIEW_FINDING_SHAPE", f"challenge {cid[:12]} against head {h.n} of #{rv.pr}: a challenge "
                         f"of a head is of item 0 and carries exactly one {FINDING} blob")
            return None
        why = self._finding_problem(cid, r, doc, h, rv)
        if why:
            self.problem(*why)
            return None
        return Finding(cid, r, doc, h)

    def _finding_problem(self, cid, r, doc, h, rv):
        where = f"finding {cid[:12]} against head {h.n} of #{rv.pr}"
        if not is_commit(doc["commit"]):
            return "REVIEW_FINDING_COMMIT_NAME", (f"{where} names commit {str(doc['commit'])[:50]!r}: a finding names the "
                                                  "head it reviewed by its full commit id, never a ref")
        if (doc["duty"], doc["pr"], doc["head"], doc["commit"], doc["tree"]) != (rv.did, rv.pr, h.tid, h.commit, h.tree):
            return "REVIEW_FINDING_HEAD", f"{where}: its blob names another duty, number, head, commit or tree"
        if not (doc["severity"] in SEVERITIES and is_line(doc["what"], 400) and isinstance(doc["where"], list)
                and len(doc["where"]) <= MAX_WHERE and all(is_line(w, 200) for w in doc["where"])
                and r["body"]["statement"] == f"{doc['severity']} {doc['what']}"):
            return "REVIEW_FINDING_SHAPE", (f"{where}: severity is one of {list(SEVERITIES)}, what one line, where at "
                                            f"most {MAX_WHERE} lines, and the statement is '<severity> <what>'")
        if doc["test"] is not None:
            why = RR.test_problem(doc["test"])
            if why:
                return "REVIEW_FINDING_TEST", f"{where}: {why}"
        later = [s for s in rv.heads if s.n > h.n and s.rec["at"] < r["at"]]
        if later:
            return "REVIEW_FINDING_SUPERSEDED", (f"{where} was filed when head {later[0].n} ({later[0].commit[:12]}) had "
                                                 "superseded it: a finding is against the current head")
        return None

    def _answers(self):
        for rv in self.reviews.values():
            for h in rv.heads:
                for a in h.answers:
                    f = self.findings.get(a)
                    if f is None or f.head.item["duty"] != rv.did or f.head.n >= h.n:
                        self.problem("REVIEW_ANSWER_UNKNOWN", f"head {h.n} of #{rv.pr} answers {a[:12]}, not a finding "
                                     "against an earlier head of this pull request")
                    elif f.answered_by is None:
                        f.answered_by = h

    def _observations(self):
        seen = set()
        for oid, r in sorted(self.recs.items(), key=lambda kv: (kv[1]["at"], kv[0])):
            if r["type"] != "observation":
                continue
            probe = self.blob(r["body"]["probe"]) or {}
            if probe.get("probe") == RR.PROBE:
                self._replay(oid, r, probe, seen)
            elif probe.get("probe") == MERGE:
                self._merge(oid, r, probe)

    def _replay(self, oid, r, probe, seen):
        where = f"replay observation {oid[:12]} by {r['actor'][:28]}"
        f = self.findings.get(probe.get("finding")) if set(probe) == set(RR.PROBE_FIELDS) else None
        if f is None or f.test is None:
            self.problem("REVIEW_REPLAY_SHAPE", f"{where}: its probe is not {list(RR.PROBE_FIELDS)} naming a mechanical finding")
            return
        rv = self.by_duty[f.head.item["duty"]]
        at = next((h for h in rv.heads if h.n >= f.head.n and h.commit == probe["commit"]), None)
        b = r["body"]
        if at is None or probe["tree"] != at.tree:
            self.problem("REVIEW_REPLAY_COMMIT", f"{where}: commit {str(probe['commit'])[:12]} is not the finding's head "
                         f"or a later head of #{rv.pr} with that tree")
            return
        if not (probe["test"] == f"{f.test['file']}:{f.test['case']}" and b["result"] in RR.RESULTS and b["raw"] == []
                and b["target"] == replay_target(self.cfg, rv.pr, f.cid, at.commit)):
            self.problem("REVIEW_REPLAY_SHAPE", f"{where}: test, result, target or raw is not the replay's")
            return
        if r["actor"] not in self.cfg["replayers"]:
            self.problem("REVIEW_REPLAYER_UNPINNED", f"{where}: .warrant/reviews.json adopts no such replayer")
            return
        if (r["actor"], f.cid, at.commit) in seen:
            self.problem("REVIEW_REPLAY_TWICE", f"{where}: the finding was replayed at {at.commit[:12]} already")
            return
        seen.add((r["actor"], f.cid, at.commit))
        f.observed[at.commit] = (oid, b["result"])

    def _merge(self, oid, r, probe):
        rv = self.by_duty.get(probe.get("duty")) if set(probe) == set(MERGE_FIELDS) else None
        b = r["body"]
        rep = self.blob(b["raw"][0]) if len(b["raw"]) == 1 else None
        ok = (rv is not None and probe["pr"] == rv.pr and is_commit(probe["merge"])
              and rep is not None and set(rep) == set(MERGE_REPORT_FIELDS) and rep["schema"] == MERGE_REPORT
              and (rep["duty"], rep["pr"], rep["merge"]) == (rv.did, rv.pr, probe["merge"])
              and all(is_commit(rep[k]) for k in ("tip", "base", "tree")) and isinstance(rep["accepted"], list)
              and all(isinstance(x, dict) and set(x) == {"transition", "commit", "by"} for x in rep["accepted"])
              and (rep["outside"] is None or (isinstance(rep["outside"], list) and rep["outside"] == sorted(rep["outside"])))
              and (rep["outside"] is None) == (rep["accepted"] == [])
              and (rep["integration"] is None or (rep["accepted"] and isinstance(rep["integration"], list)
                                                 and rep["integration"] == sorted(set(rep["integration"]))))
              and b["target"] == merge_target(self.cfg, rv.pr) and b["result"] == f"merged {probe['merge']} tip {rep['tip']}")
        if not ok:
            self.problem("REVIEW_MERGE_SHAPE", f"merge observation {oid[:12]}: its probe or report is malformed")
            return
        if rv.merges:
            self.problem("REVIEW_MERGE_TWICE", f"merge observation {oid[:12]}: #{rv.pr} has a merge observation already")
            return
        rv.merges.append((oid, r, rep))

    # -- reading

    def review(self, pr):
        rv = self.reviews.get(pr)
        if rv is None:
            raise Refused(f"no review duty of #{pr} in the view (tools/review.py open)", "REVIEW_NO_DUTY")
        return rv

    def resolve_duty(self, ref):
        if not (S.hex64(ref) and ref in self.rep["duties"]):
            raise Refused(f"{str(ref)[:70]!r} is not the full id of a duty in the view", "REVIEW_DUTY_NAME")
        return ref


def replay_target(cfg, pr, cid, commit):
    return f"{cfg['repository']}#{pr} finding {cid} at {commit}"


def merge_target(cfg, pr):
    return f"{cfg['repository']}#{pr} merged"


def merge_state(rep):
    """What a merge report establishes about the merged result, kept apart: whether a head was accepted in
    the tip's store, whether the tip changed after it, and whether the merge commit itself (its tree against
    Git's merge of the first parent with the accepted head) made changes nobody reviewed."""
    if rep["accepted"] == []:
        return NO_ACCEPTED_HEAD
    if rep["outside"]:
        return TIP_CHANGED
    if rep["integration"] is None:
        return INTEGRATION_UNVERIFIED
    return INTEGRATION_CHANGES if rep["integration"] else REVIEWED


def merged_without_acceptance(rep):
    """Whether the merged result is anything but REVIEWED (merge_state)."""
    return merge_state(rep) != REVIEWED


def finding_class(f):
    """THESIS, or the replay result at the finding's own head (NOT_REPLAYED when nobody adopted has)."""
    if f.test is None:
        return "THESIS"
    return {"FAIL": "REPRODUCED", "PASS": "NOT_REPRODUCED", None: "NOT_REPLAYED"}.get(f.at(f.head.commit), "UNEVALUABLE")


def ledger_counts(model):
    """{actor: {findings, reproduced, answered, misses}} from the review records; it grants nothing:
      findings    findings (challenges of a head carrying a finding blob) the actor filed;
      reproduced  of those, mechanical ones an adopted replayer observed failing at their own head;
      answered    of those, ones a later head of the pull request names in `answers`;
      misses      the actor's acceptances of a head at which a finding against that head reproduced
                  (whenever either was filed): the acceptor accepted what a reviewer showed failing."""
    out = {}

    def row(a):
        return out.setdefault(a, {"findings": 0, "reproduced": 0, "answered": 0, "misses": 0})

    for f in model.findings.values():
        x = row(f.rec["actor"])
        x["findings"] += 1
        x["reproduced"] += finding_class(f) == "REPRODUCED"
        x["answered"] += f.answered_by is not None
    for rv in model.reviews.values():
        for h in rv.heads:
            if any(f.head is h and finding_class(f) == "REPRODUCED" for f in rv.findings):
                for a in h.accepted_by:
                    row(a)["misses"] += 1
    return out


def repo_ledger(repo_root, recs_model):
    """ledger_counts of the repository at `repo_root` for the claims ledger (views.ledger), or {} when it
    has no .warrant/reviews.json. `recs_model` is the claims Model: its snapshot is read again here."""
    try:
        cfg = config(repo_root)
    except Refused:
        return {}
    return ledger_counts(Model(recs_model.snap, Repo(repo_root).trust(), cfg, assess=False))


# ---------------------------------------------------------------- the view

def _state(model, rv):
    r = model.rep["duties"][rv.did]
    waiting = sorted({a for h in rv.heads if h.verdict == "PENDING" for a in h.waiting})
    if r["disposition"] == "OPEN" and waiting:
        return f"{r['disposition']} · awaiting acceptance by {', '.join(waiting)}"
    return r["disposition"] + ("" if rv.heads else " · no head filed")


def _verdict(h):
    v = h.verdict or "NOT ASSESSED"
    if h.accepted_by:
        v += f" · accepted by {', '.join(h.accepted_by)}"
    elif h.waiting:
        v += f" · awaiting {', '.join(h.waiting)}"
    return v


def _merge_line(rv):
    if not rv.merges:
        return None
    oid, r, rep = rv.merges[0]
    head = (f"merge `{rep['merge'][:12]}` (tree `{rep['tree'][:12]}`), first parent `{rep['base'][:12]}`, tip "
            f"`{rep['tip'][:12]}` (observed by {r['actor']}, `{oid[:12]}`): ")
    state = merge_state(rep)
    if state == NO_ACCEPTED_HEAD:
        return head + "MERGED WITHOUT REVIEWER ACCEPTANCE: no head was accepted in the tip's store"
    last = rep["accepted"][-1]

    def paths(ps):
        return ", ".join(ps[:8]) + (" …" if len(ps) > 8 else "")
    if state == TIP_CHANGED:
        return head + (f"MERGED WITHOUT REVIEWER ACCEPTANCE: the tip changes {len(rep['outside'])} path(s) outside the "
                       f"records and their views since the accepted head `{last['commit'][:12]}`: " + paths(rep["outside"]))
    if state == INTEGRATION_CHANGES:
        return head + (f"MERGED WITH UNREVIEWED INTEGRATION CHANGES: the merge itself holds {len(rep['integration'])} "
                       f"path(s) that neither Git's merge of the first parent with the accepted head `{last['commit'][:12]}` "
                       "nor one side of a conflict gives: " + paths(rep["integration"]))
    if state == INTEGRATION_UNVERIFIED:
        return head + (f"INTEGRATION UNVERIFIED: the tip is the accepted head `{last['commit'][:12]}`, and Git could not "
                       "redo the merge here to compare the merge's own tree")
    return head + f"at the head `{last['commit'][:12]}` accepted by {', '.join(last['by'])}; the merge adds nothing else"


def render_review(model, rv):
    d = model.rep["duties"][rv.did]
    out = [f"## {model.cfg['repository']}#{rv.pr} — {rv.title}", "",
           f"- duty `{rv.did[:12]}` held by {d['holder']}, owed to {', '.join(rv.rec['body']['owed_to'])}, accepted by "
           f"{', '.join(rv.rec['body']['accept_by'])}: **{_state(model, rv)}**"]
    for x in rv.rec["body"]["serves"]:
        out.append(f"  - serves duty `{x[:12]}`")
    for h in rv.heads:
        sup = f"; superseded by head {h.successor.n}" if h.successor else ""
        ans = f"; answers {', '.join(f'`{a[:12]}`' for a in h.answers)}" if h.answers else ""
        out.append(f"- head {h.n} `{h.commit[:12]}` (tree `{h.tree[:12]}`), {h.item['act']} `{h.tid[:12]}`: "
                   f"{_verdict(h)}{sup}{ans}")
        for f in rv.findings:
            if f.head is h:
                out += _render_finding(rv, f)
    for tid, act in rv.others:
        out.append(f"- {act} `{tid[:12]}`")
    m = _merge_line(rv)
    if m:
        out.append(f"- {m}")
    return out


def _render_finding(rv, f):
    doc = f.blob
    kind = "thesis" if f.test is None else f"mechanical `{f.test['file']}:{f.test['case']}`"
    out = [f"  - finding `{f.cid[:12]}` by {f.rec['actor']}, {doc['severity']}, {kind}: {finding_class(f)} — {doc['what']}"]
    if doc["where"]:
        out.append(f"    - where: {', '.join(doc['where'])}")
    if f.test is not None:
        runs = [f"head {h.n} `{h.commit[:12]}`: {OUTCOME.get(f.at(h.commit), 'NOT REPLAYED')}" for h in rv.heads if h.n >= f.head.n]
        out.append(f"    - replayed at {'; '.join(runs)}")
    out.append(f"    - answered by head {f.answered_by.n}" if f.answered_by else "    - not answered")
    return out


def render_view(model):
    out = [
        "# Reviews (generated view)", "",
        "Generated by `python tools/review.py project` from the Warrant 2 records in",
        "`.warrant/store/`. **The records are the source; this file is a view**, and",
        "`python tools/review.py check` refuses it when it differs. It grants nothing and no",
        "rule reads it. A pull request is a duty held by its author, owed to and accepted by",
        "whom `.warrant/reviews.json` names; each pushed head is a closure naming its full",
        "commit and tree ids; a finding is a challenge of a head's closure carrying a",
        "finding blob, mechanical (a test case that must fail at the head, replayed by the",
        "review replay checker, an actor named by the hash of its code) or a thesis; an",
        "answer is a later head naming the findings it answers; an acceptance closes the",
        "duty. States are Warrant's own assessment (trust `.warrant/trust.json`, as of the",
        "latest record). A merge is a Git act: it is shown from a merge observation, and the",
        "duty stays as the records leave it.", "",
    ]
    rows = sorted(model.reviews.values(), key=lambda rv: rv.pr)
    if rows:
        out += ["| Pull request | State | Heads | Findings | Reproduced | Answered | Merge |",
                "| --- | --- | --- | --- | --- | --- | --- |"]
        for rv in rows:
            merge = MERGE_LABEL[merge_state(rv.merges[0][2])] if rv.merges else "—"
            out.append(f"| #{rv.pr} | {_state(model, rv)} | {len(rv.heads)} | {len(rv.findings)} "
                       f"| {sum(finding_class(f) == 'REPRODUCED' for f in rv.findings)} "
                       f"| {sum(f.answered_by is not None for f in rv.findings)} | {merge} |")
        out.append("")
    else:
        out += ["No review is recorded.", ""]
    without = [rv for rv in rows if rv.merges and merged_without_acceptance(rv.merges[0][2])]
    out += ["## Merged without reviewer acceptance of the result", ""]
    out += [f"- #{rv.pr}: {_merge_line(rv)}" for rv in without] or ["None."]
    out.append("")
    for rv in rows:
        out += render_review(model, rv) + [""]
    return "\n".join(out)


# ---------------------------------------------------------------- git

def _git(root, *args, ids=(), paths=(), codes=(0,)):
    """Git at `root` with object ids last before `paths`. Each id is a full lowercase object id (is_commit),
    checked here: a name never reaches Git's argument list, so none can be read as an option."""
    if not all(is_commit(x) for x in ids):
        # Its own code: every caller checks its names first (REVIEW_COMMIT_NAME); this is the last guard.
        raise Refused(f"{[str(x)[:50] for x in ids]} are not full lowercase object ids", "REVIEW_GIT_ID")
    cmd = ["git", "-C", str(root), *args, *ids] + (["--", *paths] if paths else [])
    r = subprocess.run(cmd, capture_output=True, check=False)
    if r.returncode not in codes:
        raise subprocess.CalledProcessError(r.returncode, cmd, r.stdout, r.stderr)
    return r.stdout


def resolve(root, name):
    """The commit id an operator's revision `name` (`--base origin/master`) names. The name is read by
    `git cat-file --batch-check` from standard input, never given as an argument."""
    if not (isinstance(name, str) and name and not any(c.isspace() for c in name)):
        raise Refused(f"{str(name)[:50]!r} is not a revision name", "BASE_UNREADABLE")
    r = subprocess.run(["git", "-C", str(root), "cat-file", "--batch-check"], input=f"{name}^{{commit}}\n".encode(),
                       capture_output=True, check=False)
    out = r.stdout.decode().split()
    if r.returncode or len(out) != 3 or out[1] != "commit" or not is_commit(out[0]):
        raise Refused(f"{name[:50]!r} names no commit here", "BASE_UNREADABLE")
    return out[0]


def canonical(root, name):
    """(commit, tree) for a canonical commit id in the repository at `root` (replay.canonical); REVIEW_COMMIT_NAME."""
    try:
        return RP.canonical(root, name)
    except RP.Refusal as e:
        raise Refused(str(e), "REVIEW_COMMIT_NAME") from None


def is_ancestor(root, commit):
    """Whether commit `commit` (a full id) is an ancestor of HEAD."""
    try:
        _git(root, "merge-base", "--is-ancestor", ids=(commit, resolve(root, "HEAD")))
        return True
    except subprocess.CalledProcessError:
        return False


def merge_of(root, rv, upto):
    """The merge commit that merged pull request `rv` into the history of `upto` (a full commit id), or None.
    Git's history decides, with GitHub's own label: the merge commit, `upto` or an ancestor of it, whose
    subject is `Merge pull request #<n>` followed by a space or nothing (the web merge's "… from <branch>",
    the gate's "… (accepted by …)") and which has the pull request's latest head commit as an ancestor (the
    head the records name is in what merged). More than one is REVIEW_MERGE_AMBIGUOUS: name the merge with
    `merged --pr N --merge SHA`. A squash or rebase merge leaves no such commit, and none is found."""
    last = rv.latest()
    if last is None or not (is_commit(last.commit) and is_commit(upto)):
        return None                     # both checked: the range below is built from full ids only
    subject = re.compile(rf"Merge pull request #{rv.pr}(?: |\Z)")
    rows = _git(root, "log", "--merges", "--ancestry-path", "--format=%H%x00%s", f"{last.commit}..{upto}").decode()
    found = [c for c, _, title in (r.partition("\0") for r in rows.splitlines()) if subject.match(title)]
    if len(found) > 1:
        raise Refused(f"#{rv.pr} merged at {', '.join(c[:12] for c in found)}, by their subjects: name its merge with "
                      "tools/review.py merged --pr N --merge SHA", "REVIEW_MERGE_AMBIGUOUS")
    return found[0] if found else None


def unobserved(root, model, upto):
    """[(pull request, merge commit)] of the pull requests with a review duty in `model` and no merge
    observation there that merged into the history of `upto` (merge_of), by number."""
    return [(n, mc) for n, rv in sorted(model.reviews.items()) if not rv.merges
            for mc in [merge_of(root, rv, upto)] if mc is not None]


def store_at(root, commit):
    """The Snapshot of `.warrant/store` in the tree of `commit` (a canonical id)."""
    work = Path(tempfile.mkdtemp(prefix="review-store-"))
    try:
        try:
            data = _git(root, "archive", "--format=tar", ids=(commit,), paths=(STORE,))
            with tarfile.open(fileobj=io.BytesIO(data)) as t:
                t.extractall(work, filter="data")
        except subprocess.CalledProcessError:
            pass                                # no store in that tree: no records
        return Snapshot.read(work / STORE) if (work / STORE).is_dir() else Snapshot({}, {})
    finally:
        shutil.rmtree(work, ignore_errors=True)


def _entries(root, tree):
    """{path: (mode, object id)} of the files of `tree` (a full id) outside the records and their views."""
    out = {}
    for e in _git(root, "ls-tree", "-r", "-z", ids=(tree,)).decode().split("\0"):
        if e:
            meta, path = e.split("\t", 1)
            if not ledger_path(path):
                mode, _, oid = meta.split(" ")
                out[path] = (mode, oid)
    return out


def integration(root, base, head, tree):
    """The paths outside the records and their views at which the merge's own `tree` differs from Git's merge
    of the first parent `base` with the accepted `head` (`git merge-tree --write-tree`), except a conflicted
    path that holds exactly one side's content (base's or head's): the changes the merge commit itself made,
    which nobody reviewed. None when Git cannot redo the merge here (the integration is unverified)."""
    try:
        out = _git(root, "merge-tree", "--write-tree", "--no-messages", "-z", ids=(base, head), codes=(0, 1))
    except subprocess.CalledProcessError:
        return None
    rows = out.decode().split("\0")
    conflicted = {e.split("\t", 1)[1] for e in rows[1:] if "\t" in e}
    want, got = _entries(root, rows[0]), _entries(root, tree)
    sides = (_entries(root, base), _entries(root, head))
    return sorted(p for p in set(want) | set(got) if want.get(p) != got.get(p)
                  and not (p in conflicted and got.get(p) in (sides[0].get(p), sides[1].get(p))))


def merge_report(root, trust, cfg, rv, merge):
    """The merge report blob of merge commit `merge` for review `rv`: the merge's own tree, its first parent
    (the base) and second parent (the tip); the heads accepted in the tip's own store (an acceptance filed after
    the merge is not in it); the paths the tip changes since the latest of them outside the records and their
    views; and the integration changes of the merge itself (`integration`). merge_state reads them apart."""
    merge, tree = canonical(root, merge)
    parents = _git(root, "rev-list", "--parents", "-n", "1", ids=(merge,)).decode().split()
    if len(parents) < 3:
        raise Refused(f"{merge[:12]} has {len(parents) - 1} parent(s): not a merge commit", "REVIEW_MERGE_SHAPE")
    base, tip = parents[1], parents[2]
    then = Model(store_at(root, tip), trust, cfg).by_duty.get(rv.did)
    accepted = [] if then is None else [{"transition": h.tid, "commit": h.commit, "by": h.accepted_by}
                                        for h in then.heads if h.verdict == "ADMITTED"]
    outside = integ = None
    if accepted:
        last = accepted[-1]["commit"]
        names = _git(root, "diff", "--name-only", "--no-renames", ids=(last, tip)).decode().splitlines() if last != tip else []
        outside = sorted(p for p in names if not ledger_path(p))
        integ = integration(root, base, last, tree)
    return {"schema": MERGE_REPORT, "duty": rv.did, "pr": rv.pr, "merge": merge, "tree": tree, "base": base, "tip": tip,
            "accepted": accepted, "outside": outside, "integration": integ}


