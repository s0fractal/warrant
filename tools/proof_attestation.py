#!/usr/bin/env python3
"""Creusot proofs: attested where they ran, checked where they did not.

    python3 tools/proof_attestation.py --attest   # run the proofs + mutants here, sign
    python3 tools/proof_attestation.py --check    # CI: is THIS tree's proof input attested?

The Creusot proofs (proofs/creusot/) take half an hour to install, so CI does not
run them. Instead whoever ran them signs a warrant record. Its subject is a
MANIFEST: the SHA-256 of every proof input, meaning the proved impl-rs files
(read from the crate's #[path] lines) and the files of proofs/creusot itself.
`--check` recomputes that manifest from the checkout and looks for a record about
exactly it, signed by a key that proofs/creusot/attestation/trust.json binds.

What a green --check means: CLAIMED. A trusted key says `cargo creusot` and
mutants.py passed on these exact inputs; the logs are attached as evidence. It is
not a re-run, and the output says so. It turns red when a proved file changes
without a new attestation, and it names the files that changed since the last one.
"""
import argparse
import hashlib
import json
import os
import platform
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROOFS = Path("proofs/creusot")
ATT = PROOFS / "attestation"
ACTOR = "claude@warrant-proofs"
DEFAULT_KEY = Path.home() / ".warrant" / "keys" / "claude-warrant-proofs.key"
CHECK_SCRIPT = b"cd proofs/creusot && cargo creusot && python3 mutants.py\n"
NOTE = "Creusot proofs and mutants.py ran locally; logs attached as evidence"
LOGS = PROOFS / "target" / "attestation-logs"


# DENY BY DEFAULT. Every file in the proof crate is a proof input except these,
# because Cargo and Creusot pick files up on their own (build.rs, examples/,
# benches/, .cargo/config.toml, rust-toolchain.toml), and a list of the inputs
# we thought of was shown to miss one (Codex review 2026-10-17: an added
# build.rs left the manifest unchanged and the check green while the real
# `cargo creusot` failed). What is excluded is named here and nowhere else.
NON_INPUT_DIRS = {"target", "attestation", ".why3find", "_creusot_erasure"}   # outputs and caches
NON_INPUT_FILES = {"README.md", ".gitignore"}                                  # prose, VCS
NON_INPUT_SUFFIXES = (".coma",)                                                # generated by Creusot
# Outside the crate, Cargo also reads configuration from every ancestor directory.
ANCESTOR_INPUTS = (".cargo/config", ".cargo/config.toml", "rust-toolchain", "rust-toolchain.toml",
                   "Cargo.toml", "Cargo.lock")
REFERENCE = re.compile(r'(?:#\[path\s*=\s*|include(?:_str|_bytes)?!\s*\(\s*)"([^"]+)"')


class OutsideInput(Exception):
    """A proof input that lives outside the repository cannot be attested."""


def proved_files(root):
    return sorted(p.as_posix() for p in referenced(root) if p.parts[:2] == ("impl-rs", "src"))


def crate_files(root):
    crate = root / PROOFS
    out = []
    for dirpath, dirnames, filenames in os.walk(crate):
        dirnames[:] = sorted(d for d in dirnames if d not in NON_INPUT_DIRS)
        here = Path(dirpath)
        for f in sorted(filenames):
            if f.endswith(NON_INPUT_SUFFIXES) or (here == crate and f in NON_INPUT_FILES):
                continue
            out.append((here / f).relative_to(root))
    return out


def referenced(root):
    """Files the crate's sources name by path (#[path], include!, include_str!,
    include_bytes!), resolved the way rustc resolves them: from the file's own
    directory. They are inputs wherever they live; outside the repo is refused."""
    crate = root / PROOFS
    found = set()
    for src in sorted(crate.rglob("*.rs")):
        if any(part in NON_INPUT_DIRS for part in src.relative_to(crate).parts):
            continue
        for rel in REFERENCE.findall(src.read_text(errors="replace")):
            target = (src.parent / rel).resolve()
            try:
                found.add(target.relative_to(root.resolve()))
            except ValueError:
                raise OutsideInput(f"{src.relative_to(root)} names {rel}, outside the repository") from None
    return found


def ancestor_files(root):
    out = []
    d = (root / PROOFS).parent
    while True:
        for name in ANCESTOR_INPUTS:
            if (d / name).is_file():
                out.append((d / name).relative_to(root))
        if d == root:
            return out
        d = d.parent


def input_paths(root):
    return sorted(set(crate_files(root)) | referenced(root) | set(ancestor_files(root)),
                  key=lambda q: q.as_posix())


def manifest(root):
    """`sha256  path` per proof input, sorted by path, as the bytes the record names.

    Every file of the proof crate (deny by default: see NON_INPUT_*), every file
    its sources name by path, and the Cargo configuration and toolchain files of
    its ancestor directories up to the repository root."""
    lines = [f"{hashlib.sha256((root / p).read_bytes()).hexdigest()}  {p.as_posix()}"
             for p in input_paths(root)]
    return ("\n".join(lines) + "\n").encode()


def _depinfo_deps(text):
    """The dependency paths of one Makefile-style .d file (escaped spaces kept)."""
    text = text.replace("\\\n", " ")
    for line in text.splitlines():
        if ":" in line and not line.startswith("#"):
            for tok in re.split(r"(?<!\\) ", line.split(":", 1)[1]):
                tok = tok.replace("\\ ", " ").strip()
                if tok:
                    yield tok


def depinfo_files(crate):
    """Every file rustc reports reading for this crate (its .d dep-info files)."""
    seen = set()
    for d in (crate / "target").rglob("*.d"):
        if "warrant_creusot_proofs" in d.name or "warrant-creusot-proofs" in str(d.parent):
            for tok in _depinfo_deps(d.read_text(errors="replace")):
                seen.add(Path(tok).resolve() if tok.startswith("/") else (crate / tok).resolve())
    return seen


def uncovered(root, read, inputs):
    """Repository files the compiler read that the manifest does not name."""
    base = root.resolve()
    named = {base / p for p in inputs}
    out = []
    for f in sorted(read):
        try:
            f.relative_to(base)
        except ValueError:
            continue                                  # toolchain, registry: the environment
        if f.is_file() and f not in named:
            out.append(f.relative_to(base).as_posix())
    return out


def untracked(root, inputs):
    """Inputs git does not track: present here, absent from the checkout CI sees.
    Lists every tracked file and compares in Python, so no path reaches argv."""
    r = subprocess.run(["git", "ls-files", "-z"], cwd=root, capture_output=True, check=False)
    tracked = set(r.stdout.decode().split("\0")) - {""}
    return [p.as_posix() for p in inputs if p.as_posix() not in tracked]


def warrant(root, *args, **kw):
    return subprocess.run([sys.executable, str(root / "impl" / "warrant.py"),
                           "--store", str(root / ATT / "store"), *args],
                          capture_output=True, check=False, **kw)


def blob(root, data):
    with tempfile.NamedTemporaryFile(delete=False) as f:
        f.write(data)
    try:
        r = warrant(root, "blob", "add", f.name, text=True)
    finally:
        os.unlink(f.name)
    if r.returncode != 0:
        sys.exit(f"blob add failed: {r.stderr}")
    return r.stdout.strip()


def run_logged(argv, cwd):
    r = subprocess.run(argv, cwd=cwd, stdin=subprocess.DEVNULL, capture_output=True, text=True, check=False)
    return r.returncode, r.stdout + r.stderr


def _saved_logs(root):
    """Logs a passing run saved for THESE inputs (a failed propose should not
    cost another proof run); anything else is refused."""
    logs = root / LOGS
    saved = json.loads((logs / "run.json").read_text())
    if saved["manifest"] != hashlib.sha256(manifest(root)).hexdigest():
        sys.exit("saved logs are for other proof inputs; run --attest without --reuse-logs")
    return (logs / "creusot.log").read_text(), (logs / "mutants.log").read_text()


def _fresh_logs(root):
    code, proof_log = run_logged(["cargo", "creusot"], root / PROOFS)
    if code != 0 or "Proved" not in proof_log:
        sys.exit("cargo creusot did not prove everything; nothing attested\n" + proof_log[-2000:])
    code, mutant_log = run_logged([sys.executable, "-u", "mutants.py"], root / PROOFS)
    if code != 0:
        sys.exit("mutants.py: not every mutant was killed; nothing attested\n" + mutant_log[-2000:])
    logs = root / LOGS
    logs.mkdir(parents=True, exist_ok=True)
    (logs / "creusot.log").write_text(proof_log)
    (logs / "mutants.log").write_text(mutant_log)
    (logs / "run.json").write_text(json.dumps({"manifest": hashlib.sha256(manifest(root)).hexdigest()}))
    return proof_log, mutant_log


def _refuse_uncovered(root):
    inputs = input_paths(root)
    missed = uncovered(root, depinfo_files(root / PROOFS), inputs)
    if missed:
        sys.exit("the compiler read repository files the manifest does not name; nothing attested: "
                 + ", ".join(missed))
    loose = untracked(root, inputs)
    if loose:
        sys.exit("proof inputs not tracked by git (CI would not see them); commit or remove them first: "
                 + ", ".join(loose))


def attest(root, key, reuse_logs=False):
    if not key.is_file():
        sys.exit(f"no key at {key} (set WARRANT_PROOFS_KEY)")
    proof_log, mutant_log = _saved_logs(root) if reuse_logs else _fresh_logs(root)
    _refuse_uncovered(root)
    creusot = subprocess.run(["git", "-C", str(Path.home() / "Projects" / "creusot"), "rev-parse", "HEAD"],
                             capture_output=True, text=True, check=False).stdout.strip() or "unknown"
    env = json.dumps({"creusot_commit": creusot, "platform": platform.platform(),
                      "why3find_json": json.loads((root / PROOFS / "why3find.json").read_text())},
                     indent=2, sort_keys=True).encode()
    if not (root / ATT / "store").is_dir():
        warrant(root, "init")
    man = blob(root, manifest(root))
    policy = blob(root, (root / ATT / "POLICY.md").read_bytes())
    check = blob(root, CHECK_SCRIPT)
    evidence = [blob(root, proof_log.encode()), blob(root, mutant_log.encode()), blob(root, env)]
    summary = proof_log.strip().splitlines()[-1] + "; " + mutant_log.strip().splitlines()[-1]
    args = ["propose", "--subject", man, "--under", policy, "--note", NOTE,
            "--check", check, "--runtime", "cmd@v1", "--verdict", "pass",
            "--actor", ACTOR, "--key", str(key)]
    for e in evidence:
        args += ["--evidence", e]
    r = warrant(root, *args, text=True)
    if r.returncode != 0:
        sys.exit(f"propose failed: {r.stderr}")
    print(f"attested manifest {man} as {r.stdout.strip()}: {summary}")
    return 0


def records(root):
    out = []
    for p in sorted((root / ATT / "store" / "records").glob("*.json")):
        try:
            out.append(json.loads(p.read_text()))
        except (OSError, ValueError):
            continue
    return out


def changed_since(old, new):
    def parse(text):
        return {line[66:]: line[:64] for line in text.splitlines() if len(line) > 66}
    a, b = parse(old), parse(new)
    return sorted(p for p in set(a) | set(b) if a.get(p) != b.get(p))


def _store_errors(root, trust_path):
    """None if the attestation store verifies at settlement grade, else why not."""
    r = warrant(root, "verify", "--settlement", "--require-bound", "--trust-config", str(trust_path),
                "--json", text=True)
    try:
        report = json.loads(r.stdout)
    except ValueError:
        return f"the attestation store does not verify: {r.stderr.strip()[:300]}"
    if report.get("errors") != 0:
        errs = [f for f in report.get("findings", []) if f.get("level") == "ERR"]
        return f"the attestation store has {report.get('errors')} error(s): {errs[:3]}"
    return None


def _broken_evidence(body, blobs):
    return [h for h in body.get("evidence", []) + [body["subject"]["hash"]]
            if not (blobs / h).is_file() or hashlib.sha256((blobs / h).read_bytes()).hexdigest() != h]


def _explain_missing(mine, blobs, current):
    if mine:
        last = max(mine, key=lambda e: e["body"]["ts"])["body"]["subject"]["hash"]
        if (blobs / last).is_file():
            diff = changed_since((blobs / last).read_text(), current.decode())
            print("      changed since the last attestation: " + ", ".join(diff[:12]))
    print("      run the proofs where Creusot is installed: python3 tools/proof_attestation.py --attest")


def check(root):
    trust_path = root / ATT / "trust.json"
    trusted = set(json.loads(trust_path.read_text()).get("actors", {}))
    try:
        current = manifest(root)
    except OutsideInput as e:
        print(f"FAIL  {e}: an input CI cannot see cannot be attested")
        return 1
    want = hashlib.sha256(current).hexdigest()
    why = _store_errors(root, trust_path)
    if why:
        print(f"FAIL  {why}")
        return 1
    blobs = root / ATT / "store" / "blobs"
    mine = [e for e in records(root) if e["body"].get("actor", {}).get("id") in trusted
            and e["body"].get("decision") == "propose"]
    for b in (e["body"] for e in mine if e["body"]["subject"]["hash"] == want):
        missing = _broken_evidence(b, blobs)
        if missing:
            print(f"FAIL  the record for this manifest lacks intact evidence: {missing}")
            return 1
        print(f"PROOFS: CLAIMED by {b['actor']['id']} (ts {b['ts']}) for manifest {want[:16]}…; "
              f"not re-run here. {b['subject'].get('note', '')}")
        return 0
    print(f"FAIL  no trusted attestation for this tree's proof inputs (manifest {want[:16]}…).")
    _explain_missing(mine, blobs, current)
    return 1


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--attest", action="store_true")
    g.add_argument("--check", action="store_true")
    g.add_argument("--manifest", action="store_true", help="print the manifest of this tree")
    ap.add_argument("--root", type=Path, default=ROOT)
    ap.add_argument("--reuse-logs", action="store_true",
                    help="with --attest: sign the logs a passing run saved for these same inputs")
    args = ap.parse_args()
    if args.manifest:
        sys.stdout.write(manifest(args.root).decode())
        return 0
    if args.attest:
        return attest(args.root, Path(os.environ.get("WARRANT_PROOFS_KEY", DEFAULT_KEY)), args.reuse_logs)
    return check(args.root)


if __name__ == "__main__":
    sys.exit(main())
