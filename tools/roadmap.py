CONFIG = "warrant-roadmap/config@1"
CONFIG_FIELDS = ("roadmap", "owed_to", "accept_by", "results_accept_by")
REVISION = "warrant-roadmap/revision@1"
REVISION_FIELDS = ("schema", "goal", "act", "because", "refs")
